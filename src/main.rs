// ----- per-user settings ----------------------------------------------------------------

#[derive(Debug, Default, Serialize, Deserialize)]
struct Config {
    recent: Vec<Recent>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct Recent {
    name: String,
    path: String,
}

fn config_path() -> Option<PathBuf> {
    directories::ProjectDirs::from("", "", form1099keep::FOLDER)
        .map(|d| d.config_dir().join("settings.json"))
}

impl Config {
    fn load() -> Self {
        config_path()
            .and_then(|p| std::fs::read(p).ok())
            .and_then(|b| serde_json::from_slice(&b).ok())
            .unwrap_or_default()
    }

    fn save(&self) {
        if let Some(p) = config_path() {
            if let Some(dir) = p.parent() {
                let _ = std::fs::create_dir_all(dir);
            }
            if let Ok(b) = serde_json::to_vec_pretty(self) {
                let _ = std::fs::write(p, b);
            }
        }
    }

    fn remember(&mut self, name: &str, path: &Path) {
        let p = path.display().to_string();
        self.recent.retain(|r| r.path != p);
        self.recent.insert(
            0,
            Recent {
                name: name.to_owned(),
                path: p,
            },
        );
        self.recent.truncate(8);
        self.save();
    }
}

// ----- controller state ------------------------------------------------------------------

#[derive(Debug, Clone)]
enum Person {
    Payer(Payer),
    Recipient(Recipient),
}

#[derive(Default)]
struct State {
    book: Option<Book>,
    config: Config,
    year: i32,
    years: Vec<i32>,
    loaded: Option<Year>,
    payer_ids: Vec<String>,
    recipient_ids: Vec<String>,
    /// The form being edited (box values are read back from the window on save).
    form: Option<Form>,
    person: Option<Person>,
    pending_open: Option<PathBuf>,
    /// A MoneyKeep book that is not yet a 1099 book, waiting for the user to confirm
    /// opening it as one (security-review-1 M6).
    pending_mark: Option<Book>,
    /// After the recovery key is shown: the book to show.
    after_recovery: Option<Book>,
}

type Shared = Rc<RefCell<State>>;

fn s(x: impl Into<SharedString>) -> SharedString {
    x.into()
}

fn model<T: Clone + 'static>(v: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(v))
}

fn note(tone: i32, text: impl Into<SharedString>) -> Note {
    Note {
        tone,
        text: text.into(),
    }
}

fn tone_of(sev: Severity) -> i32 {
    match sev {
        Severity::Error => 2,
        Severity::Warning => 4,
        Severity::Note => 1,
    }
}

/// The tax year being prepared: this calendar year from July, else last year.
fn default_year() -> i32 {
    let now = time::OffsetDateTime::now_local().unwrap_or_else(|_| time::OffsetDateTime::now_utc());
    let y = if u8::from(now.month()) >= 7 {
        now.year()
    } else {
        now.year().saturating_sub(1)
    };
    y.max(form1099keep::FIRST_YEAR)
}

fn today() -> String {
    let now = time::OffsetDateTime::now_local().unwrap_or_else(|_| time::OffsetDateTime::now_utc());
    format!(
        "{:04}-{:02}-{:02}",
        now.year(),
        u8::from(now.month()),
        now.day()
    )
}

fn parse_amount(label: &str, t: &str) -> Result<Decimal, Error> {
    let c: String = t
        .chars()
        .filter(|c| !matches!(c, '$' | ',' | ' '))
        .collect();
    if c.is_empty() {
        return Ok(Decimal::ZERO);
    }
    Decimal::from_str(&c).map_err(|_| Error::invalid(format!("{label}: {t:?} is not an amount")))
}

fn amount_text(d: Decimal) -> String {
    if d.is_zero() {
        String::new()
    } else {
        check::money(d)
    }
}

fn show_message(ui: &AppWindow, tone: i32, text: impl Into<SharedString>) {
    ui.set_message(text.into());
    ui.set_message_tone(tone);
}

fn show_error(ui: &AppWindow, e: &Error) {
    show_message(ui, 2, e.to_string());
}

// ----- refreshing the window --------------------------------------------------------------

fn refresh(ui: &AppWindow, st: &mut State) {
    let Some(book) = st.book.as_mut() else {
        ui.set_book_open(false);
        ui.set_recent(model(
            st.config
                .recent
                .iter()
                .map(|r| RecentBook {
                    name: s(r.name.as_str()),
                    path: s(r.path.as_str()),
                })
                .collect(),
        ));
        return;
    };
    ui.set_book_open(true);
    ui.set_book_name(s(book.name()));
    ui.set_book_encrypted(book.is_encrypted());

    let mut years = book.years().unwrap_or_default();
    let dy = default_year();
    if !years.contains(&dy) {
        years.push(dy);
    }
    if !years.contains(&st.year) {
        years.push(st.year);
    }
    years.sort_unstable_by(|a, b| b.cmp(a));
    years.dedup();
    ui.set_years(model(years.iter().map(|y| s(y.to_string())).collect()));
    ui.set_year_index(years.iter().position(|y| *y == st.year).unwrap_or(0) as i32);
    st.years = years;

    let payers = book.payers().unwrap_or_default();
    let recipients = book.recipients().unwrap_or_default();
    st.payer_ids = payers.iter().map(|p| p.id.clone()).collect();
    st.recipient_ids = recipients.iter().map(|r| r.id.clone()).collect();
    ui.set_payer_names(model(payers.iter().map(|p| s(p.name.as_str())).collect()));
    ui.set_recipient_names(model(
        recipients
            .iter()
            .map(|r| {
                let city = r.address.city.trim();
                if city.is_empty() {
                    s(r.display_name())
                } else {
                    s(format!("{} ({city})", r.display_name()))
                }
            })
            .collect(),
    ));

    match Year::load(book, st.year) {
        Ok(y) => {
            let mut rows = Vec::new();
            let mut needs = 0usize;
            let (mut ready, mut filed) = (0usize, 0usize);
            let mut total = Decimal::ZERO;
            for f in &y.forms {
                let mine = check::for_form(&y.findings, f);
                let errors = mine
                    .iter()
                    .filter(|x| x.severity == Severity::Error)
                    .count();
                let warnings = mine
                    .iter()
                    .filter(|x| x.severity == Severity::Warning)
                    .count();
                if errors > 0 {
                    needs = needs.saturating_add(1);
                }
                match f.status {
                    Status::Ready => ready = ready.saturating_add(1),
                    Status::Filed => filed = filed.saturating_add(1),
                    Status::Draft => {}
                }
                total = total.checked_add(f.income_total()).unwrap_or(total);
                let (issues, issues_tone) = if errors > 0 {
                    (format!("{errors} to answer"), 2)
                } else if warnings > 0 {
                    (format!("{warnings} to check"), 4)
                } else {
                    (String::new(), 1)
                };
                rows.push(FormRow {
                    id: s(f.id.as_str()),
                    recipient: s(y
                        .recipients
                        .get(&f.recipient)
                        .map(Recipient::display_name)
                        .unwrap_or_default()),
                    kind: s(if f.corrected {
                        format!("{} · corrected", f.kind.label())
                    } else {
                        f.kind.label().to_owned()
                    }),
                    total: s(format!("${}", check::money(f.income_total()))),
                    status: s(f.status.label()),
                    status_tone: match f.status {
                        Status::Draft => 1,
                        Status::Ready => 5,
                        Status::Filed => 3,
                    },
                    issues: s(issues),
                    issues_tone,
                });
            }
            let n = y.forms.len();
            let mut summary = format!(
                "{n} form{} · ${}",
                if n == 1 { "" } else { "s" },
                check::money(total)
            );
            if needs > 0 {
                summary.push_str(&format!(" · {needs} need answers"));
            }
            if ready > 0 {
                summary.push_str(&format!(" · {ready} ready"));
            }
            if filed > 0 {
                summary.push_str(&format!(" · {filed} filed"));
            }
            if let Some(x) = y
                .findings
                .iter()
                .find(|x| matches!(x.subject, Subject::Year(_)))
            {
                summary.push_str(" · ");
                summary.push_str(&x.message);
            }
            ui.set_forms_summary(s(summary));
            ui.set_forms(model(rows));
            ui.set_issue_count(needs as i32);
            ui.set_ready_count(ready as i32);
            st.loaded = Some(y);
        }
        Err(e) => show_error(ui, &e),
    }
    refresh_people(ui, st);
}

fn refresh_people(ui: &AppWindow, st: &mut State) {
    let Some(book) = st.book.as_mut() else { return };
    let payers_view = ui.get_people_payers();
    let rows: Vec<PersonRow> = if payers_view {
        book.payers()
            .unwrap_or_default()
            .iter()
            .map(|p| {
                let errors = check::payer(p)
                    .iter()
                    .filter(|x| x.severity == Severity::Error)
                    .count();
                PersonRow {
                    id: s(p.id.as_str()),
                    name: s(p.name.as_str()),
                    detail: s(p.address.city_line()),
                    tin: s(p.masked_tin()),
                    issues: s(if errors > 0 {
                        format!("{errors} to answer")
                    } else {
                        String::new()
                    }),
                }
            })
            .collect()
    } else {
        book.recipients()
            .unwrap_or_default()
            .iter()
            .map(|r| {
                let errors = check::recipient(r)
                    .iter()
                    .filter(|x| x.severity == Severity::Error)
                    .count();
                let mut detail = r.address.city_line();
                if r.source.is_some() {
                    detail.push_str(if detail.is_empty() {
                        "from MoneyKeep"
                    } else {
                        " · from MoneyKeep"
                    });
                }
                PersonRow {
                    id: s(r.id.as_str()),
                    name: s(r.display_name()),
                    detail: s(detail),
                    tin: s(if r.tin.is_empty() {
                        "no TIN".to_owned()
                    } else {
                        r.masked_tin()
                    }),
                    issues: s(if errors > 0 {
                        format!("{errors} to answer")
                    } else {
                        String::new()
                    }),
                }
            })
            .collect()
    };
    ui.set_people(model(rows));
}

/// A book was opened: show it if it is a 1099 book; otherwise ask first whether to use it
/// as one, since that writes Form1099Keep's marker into it (security-review-1 M6).
fn opened(ui: &AppWindow, st: &mut State, book: Book) {
    match book.is_1099_book() {
        Ok(true) => after_open(ui, st, book),
        Ok(false) => {
            ui.set_d_text(s(format!(
                "{} is a MoneyKeep book that Form1099Keep hasn't used yet. Opening it as a 1099 book \
                 marks it as one; its other contents are not changed.",
                book.path().map_or_else(|| book.name(), |p| p.display().to_string())
            )));
            st.pending_mark = Some(book);
            ui.set_dialog(7);
        }
        Err(e) => show_error(ui, &e),
    }
}

fn after_open(ui: &AppWindow, st: &mut State, book: Book) {
    if let Some(p) = book.path() {
        st.config.remember(&book.name(), p);
    }
    st.book = Some(book);
    st.year = default_year();
    st.form = None;
    st.person = None;
    ui.set_form_editing(false);
    ui.set_person_editing(false);
    ui.set_selected_form(s(""));
    ui.set_selected_person(s(""));
    ui.set_message(s(""));
    ui.set_im_year(s(st.year.to_string()));
    ui.set_filed_date(s(today()));
    ui.set_im_result(model(Vec::new()));
    ui.set_out_result(model(Vec::new()));
    refresh(ui, st);
    // A new book starts where the work starts, on Payers; otherwise on Forms.
    let section = if st.payer_ids.is_empty() { 0 } else { 3 };
    ui.set_people_payers(section == 0);
    ui.set_section(section);
    refresh_people(ui, st);
    if !st.book.as_ref().is_some_and(Book::is_encrypted) {
        show_message(
            ui,
            4,
            "This book is not password protected, so it cannot hold taxpayer id numbers. \
             Choose “Protect with a password…”.",
        );
    }
}

// ----- the form editor ---------------------------------------------------------------------

fn box_fields(f: &Form) -> Vec<BoxField> {
    boxes::layout(f.kind)
        .iter()
        .map(|b| BoxField {
            key: s(b.key),
            title: s(b.title()),
            kind: match b.kind {
                BoxKind::Amount => 0,
                BoxKind::Check => 1,
                BoxKind::Codes => 2,
            },
            value: s(match b.kind {
                BoxKind::Amount => amount_text(f.amount(b.key)),
                BoxKind::Codes => f.ttoc.join(", "),
                BoxKind::Check => String::new(),
            }),
            checked: f.checked(b.key),
            bold: b.bold,
        })
        .collect()
}

fn show_form(ui: &AppWindow, st: &State, f: &Form) {
    let is_new = f.id.is_empty();
    ui.set_form_editing(true);
    ui.set_selected_form(s(f.id.as_str()));
    ui.set_f_is_new(is_new);
    ui.set_form_heading(s(if is_new {
        "New form".to_owned()
    } else {
        format!("Form {}", f.kind.label())
    }));
    ui.set_f_payer(
        st.payer_ids
            .iter()
            .position(|x| *x == f.payer)
            .map_or(-1, |i| i as i32),
    );
    ui.set_f_recipient(
        st.recipient_ids
            .iter()
            .position(|x| *x == f.recipient)
            .map_or(-1, |i| i as i32),
    );
    ui.set_f_kind(match f.kind {
        FormKind::Nec => 0,
        FormKind::Misc => 1,
    });
    ui.set_f_year(s(f.tax_year.to_string()));
    ui.set_f_boxes(model(box_fields(f)));
    ui.set_f_account(s(f.account_number.as_str()));
    ui.set_f_second_tin(f.second_tin_notice);
    let st_row = |i: usize| f.states.get(i).cloned().unwrap_or_default();
    let (a, b) = (st_row(0), st_row(1));
    ui.set_s1_state(s(a.state));
    ui.set_s1_no(s(a.payer_state_no));
    ui.set_s1_withheld(s(amount_text(a.tax_withheld)));
    ui.set_s1_income(s(amount_text(a.income)));
    ui.set_s2_state(s(b.state));
    ui.set_s2_no(s(b.payer_state_no));
    ui.set_s2_withheld(s(amount_text(b.tax_withheld)));
    ui.set_s2_income(s(amount_text(b.income)));
    ui.set_f_notes(s(f.notes.as_str()));
    let status = match (&f.status, &f.filed) {
        (Status::Filed, Some(x)) if !x.date.is_empty() => format!("Filed {}", x.date),
        (st, _) => st.label().to_owned(),
    };
    ui.set_f_status(s(status));
    ui.set_f_filed(f.is_filed());
    ui.set_f_corrected(f.corrected);
    let notes: Vec<Note> = match (&st.loaded, is_new) {
        (Some(y), false) => check::for_form(&y.findings, f)
            .into_iter()
            .map(|x| note(tone_of(x.severity), x.message.as_str()))
            .collect(),
        _ => Vec::new(),
    };
    ui.set_f_findings(model(notes));
}

/// The form as edited in the window.
fn form_from_ui(ui: &AppWindow, st: &State) -> Result<Form, Error> {
    let mut f = st.form.clone().unwrap_or_default();
    let pi = ui.get_f_payer();
    let ri = ui.get_f_recipient();
    f.payer = usize::try_from(pi)
        .ok()
        .and_then(|i| st.payer_ids.get(i).cloned())
        .ok_or_else(|| Error::invalid("Choose the payer (add one under Payers first)."))?;
    f.recipient = usize::try_from(ri)
        .ok()
        .and_then(|i| st.recipient_ids.get(i).cloned())
        .ok_or_else(|| Error::invalid("Choose the recipient (add one under Recipients first)."))?;
    f.kind = if ui.get_f_kind() == 1 {
        FormKind::Misc
    } else {
        FormKind::Nec
    };
    f.tax_year = ui
        .get_f_year()
        .trim()
        .parse()
        .map_err(|_| Error::invalid("The tax year should be a year such as 2026."))?;
    f.amounts.clear();
    f.checks.clear();
    f.ttoc.clear();
    let rows = ui.get_f_boxes();
    for i in 0..rows.row_count() {
        let Some(b) = rows.row_data(i) else { continue };
        match b.kind {
            0 => {
                let v = parse_amount(&b.title, &b.value)?;
                f.set_amount(&b.key, v);
            }
            1 => f.set_check(&b.key, b.checked),
            _ => {
                f.ttoc = b
                    .value
                    .split([',', ' '])
                    .map(str::trim)
                    .filter(|c| !c.is_empty())
                    .map(str::to_owned)
                    .collect();
            }
        }
    }
    f.account_number = ui.get_f_account().trim().to_owned();
    f.second_tin_notice = ui.get_f_second_tin();
    f.notes = ui.get_f_notes().to_string();
    f.states.clear();
    for (state, no, w, inc) in [
        (
            ui.get_s1_state(),
            ui.get_s1_no(),
            ui.get_s1_withheld(),
            ui.get_s1_income(),
        ),
        (
            ui.get_s2_state(),
            ui.get_s2_no(),
            ui.get_s2_withheld(),
            ui.get_s2_income(),
        ),
    ] {
        if [&state, &no, &w, &inc].iter().all(|x| x.trim().is_empty()) {
            continue;
        }
        f.states.push(StateRow {
            state: state.trim().to_ascii_uppercase(),
            payer_state_no: no.trim().to_owned(),
            tax_withheld: parse_amount("State tax withheld", &w)?,
            income: parse_amount("State income", &inc)?,
        });
    }
    Ok(f)
}

// ----- the person editor --------------------------------------------------------------------

fn show_person(ui: &AppWindow, p: &Person) {
    ui.set_person_editing(true);
    let (is_payer, id, addr, email, findings) = match p {
        Person::Payer(x) => (
            true,
            x.id.clone(),
            x.address.clone(),
            x.email.clone(),
            check::payer(x),
        ),
        Person::Recipient(x) => (
            false,
            x.id.clone(),
            x.address.clone(),
            x.email.clone(),
            check::recipient(x),
        ),
    };
    ui.set_p_is_payer(is_payer);
    ui.set_p_is_new(id.is_empty());
    ui.set_selected_person(s(id.as_str()));
    match p {
        Person::Payer(x) => {
            ui.set_p_name_type(0);
            ui.set_p_business(s(x.name.as_str()));
            ui.set_p_business2(s(x.name2.as_str()));
            ui.set_p_tin_type(if x.tin_type == TinType::Ssn { 1 } else { 0 });
            ui.set_p_tin(s(form1099keep::tin::display(Some(x.tin_type), &x.tin)));
            ui.set_p_phone(s(x.phone.as_str()));
            ui.set_p_account(s(""));
            ui.set_p_source(s(""));
        }
        Person::Recipient(x) => {
            ui.set_p_name_type(if x.name_type == NameType::Person {
                1
            } else {
                0
            });
            ui.set_p_business(s(x.business_name.as_str()));
            ui.set_p_business2(s(x.business_name2.as_str()));
            ui.set_p_first(s(x.first.as_str()));
            ui.set_p_middle(s(x.middle.as_str()));
            ui.set_p_last(s(x.last.as_str()));
            ui.set_p_suffix(s(x.suffix.as_str()));
            ui.set_p_tin_type(match x.tin_type {
                None => 0,
                Some(TinType::Ein) => 1,
                Some(TinType::Ssn) => 2,
                Some(TinType::Itin) => 3,
                Some(TinType::Atin) => 4,
            });
            ui.set_p_tin(s(form1099keep::tin::display(x.tin_type, &x.tin)));
            ui.set_p_phone(s(""));
            ui.set_p_account(s(x.account_number.as_str()));
            ui.set_p_source(s(x
                .source
                .as_ref()
                .map(|src| {
                    format!(
                        "Imported from MoneyKeep book “{}” (vendor {}).",
                        src.book_name, src.vendor_name
                    )
                })
                .unwrap_or_default()));
        }
    }
    ui.set_p_line1(s(addr.line1));
    ui.set_p_line2(s(addr.line2));
    ui.set_p_city(s(addr.city));
    ui.set_p_state(s(addr.state));
    ui.set_p_zip(s(addr.zip));
    ui.set_p_country(s(addr.country));
    ui.set_p_email(s(email));
    let notes: Vec<Note> = if id.is_empty() {
        Vec::new()
    } else {
        findings
            .iter()
            .map(|x| note(tone_of(x.severity), x.message.as_str()))
            .collect()
    };
    ui.set_p_findings(model(notes));
}

fn person_from_ui(ui: &AppWindow, base: &Person) -> Person {
    let address = Address {
        line1: ui.get_p_line1().trim().to_owned(),
        line2: ui.get_p_line2().trim().to_owned(),
        city: ui.get_p_city().trim().to_owned(),
        state: ui.get_p_state().trim().to_ascii_uppercase(),
        zip: ui.get_p_zip().trim().to_owned(),
        country: {
            let c = ui.get_p_country().trim().to_owned();
            if c.is_empty() { "US".into() } else { c }
        },
    };
    match base {
        Person::Payer(p) => Person::Payer(Payer {
            name: ui.get_p_business().trim().to_owned(),
            name2: ui.get_p_business2().trim().to_owned(),
            tin_type: if ui.get_p_tin_type() == 1 {
                TinType::Ssn
            } else {
                TinType::Ein
            },
            tin: ui.get_p_tin().to_string(),
            address,
            phone: ui.get_p_phone().trim().to_owned(),
            email: ui.get_p_email().trim().to_owned(),
            ..p.clone()
        }),
        Person::Recipient(r) => Person::Recipient(Recipient {
            name_type: if ui.get_p_name_type() == 1 {
                NameType::Person
            } else {
                NameType::Business
            },
            business_name: ui.get_p_business().trim().to_owned(),
            business_name2: ui.get_p_business2().trim().to_owned(),
            first: ui.get_p_first().trim().to_owned(),
            middle: ui.get_p_middle().trim().to_owned(),
            last: ui.get_p_last().trim().to_owned(),
            suffix: ui.get_p_suffix().trim().to_owned(),
            tin_type: match ui.get_p_tin_type() {
                1 => Some(TinType::Ein),
                2 => Some(TinType::Ssn),
                3 => Some(TinType::Itin),
                4 => Some(TinType::Atin),
                _ => None,
            },
            tin: ui.get_p_tin().to_string(),
            address,
            email: ui.get_p_email().trim().to_owned(),
            account_number: ui.get_p_account().trim().to_owned(),
            ..r.clone()
        }),
    }
}

// ----- wiring ---------------------------------------------------------------------------------

fn open_path(ui: &AppWindow, st: &mut State, path: PathBuf) {
    match mk_store::book_kind(&path) {
        Ok(mk_store::BookKind::Encrypted) => {
            ui.set_d_text(s(format!("Enter the password for {}.", path.display())));
            ui.set_d_password(s(""));
            ui.set_d_error(s(""));
            st.pending_open = Some(path);
            ui.set_dialog(2);
        }
        Ok(mk_store::BookKind::Plain) => match Book::open(&path, None) {
            Ok(b) => opened(ui, st, b),
            Err(e) => show_error(ui, &e),
        },
        Err(e) => show_error(ui, &Error::from(e)),
    }
}

fn wire(ui: &AppWindow, state: &Shared) {
    macro_rules! on {
        ($name:ident, |$ui:ident, $st:ident $(, $arg:ident : $t:ty)*| $body:block) => {{
            let weak = ui.as_weak();
            let state = state.clone();
            ui.$name(move |$($arg: $t),*| {
                let Some($ui) = weak.upgrade() else { return };
                let mut guard = state.borrow_mut();
                let $st: &mut State = &mut guard;
                $body
            });
        }};
    }

    on!(on_dismiss_message, |ui, _st| {
        ui.set_message(s(""));
    });
    on!(on_dialog_cancel, |ui, st| {
        st.pending_open = None;
        st.pending_mark = None;
        ui.set_d_password(s(""));
        ui.set_d_password2(s(""));
        ui.set_dialog(0);
    });

    on!(on_new_book, |ui, _st| {
        ui.set_d_name(s(""));
        ui.set_d_password(s(""));
        ui.set_d_password2(s(""));
        ui.set_d_error(s(""));
        ui.set_dialog(1);
    });

    on!(on_create_book, |ui, st| {
        let name = ui.get_d_name().trim().to_owned();
        let pw = ui.get_d_password().to_string();
        if name.is_empty() {
            ui.set_d_error(s("Give the book a name."));
            return;
        }
        if pw != ui.get_d_password2().as_str() {
            ui.set_d_error(s("The two passwords differ."));
            return;
        }
        if let Err(e) = mk_store::check_password_rules(&pw) {
            ui.set_d_error(s(e.to_string()));
            return;
        }
        let file = format!(
            "{}.{}",
            name.replace(['/', '\\', ':'], "-"),
            form1099keep::BOOK_EXTENSION
        );
        let Some(path) = rfd::FileDialog::new()
            .set_title("Save the new 1099 book")
            .set_file_name(file)
            .add_filter("MoneyKeep book", &[form1099keep::BOOK_EXTENSION])
            .save_file()
        else {
            return;
        };
        match Book::create(&path, &name, &pw) {
            Ok((book, key)) => {
                ui.set_d_password(s(""));
                ui.set_d_password2(s(""));
                ui.set_recovery_key(s(key));
                st.after_recovery = Some(book);
                ui.set_dialog(3);
            }
            Err(e) => ui.set_d_error(s(e.to_string())),
        }
    });

    on!(on_recovery_done, |ui, st| {
        ui.set_recovery_key(s(""));
        ui.set_dialog(0);
        if let Some(b) = st.after_recovery.take() {
            after_open(&ui, st, b);
            show_message(&ui, 3, "Book ready. Start with Payers: add who pays.");
        } else {
            refresh(&ui, st);
            show_message(&ui, 3, "The book is now password protected.");
        }
    });

    on!(on_open_book, |ui, st| {
        if let Some(path) = rfd::FileDialog::new()
            .set_title("Open a 1099 book")
            .add_filter("MoneyKeep book", &[form1099keep::BOOK_EXTENSION])
            .pick_file()
        {
            open_path(&ui, st, path);
        }
    });

    on!(on_open_recent, |ui, st, path: SharedString| {
        let p = PathBuf::from(path.as_str());
        if !p.exists() {
            st.config.recent.retain(|r| r.path != path.as_str());
            st.config.save();
            refresh(&ui, st);
            show_message(&ui, 2, format!("{} is no longer there.", p.display()));
            return;
        }
        open_path(&ui, st, p);
    });

    on!(on_unlock, |ui, st| {
        let Some(path) = st.pending_open.clone() else {
            return;
        };
        let pw = ui.get_d_password().to_string();
        match Book::open(&path, Some(&pw)) {
            Ok(b) => {
                ui.set_d_password(s(""));
                ui.set_dialog(0);
                st.pending_open = None;
                opened(&ui, st, b);
            }
            Err(e) => ui.set_d_error(s(e.to_string())),
        }
    });

    // security-review-1 M6: the user confirmed opening a MoneyKeep book as a 1099 book.
    on!(on_confirm_mark, |ui, st| {
        ui.set_dialog(0);
        let Some(mut b) = st.pending_mark.take() else {
            return;
        };
        match b.mark() {
            Ok(()) => after_open(&ui, st, b),
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_close_book, |ui, st| {
        st.book = None;
        st.loaded = None;
        st.form = None;
        st.person = None;
        ui.set_form_editing(false);
        ui.set_person_editing(false);
        ui.set_message(s(""));
        refresh(&ui, st);
    });

    on!(on_protect_book, |ui, st| {
        if ui.get_dialog() != 4 {
            ui.set_d_password(s(""));
            ui.set_d_password2(s(""));
            ui.set_d_error(s(""));
            ui.set_dialog(4);
            return;
        }
        let pw = ui.get_d_password().to_string();
        if pw != ui.get_d_password2().as_str() {
            ui.set_d_error(s("The two passwords differ."));
            return;
        }
        let Some(book) = st.book.as_mut() else { return };
        match book.protect(&pw) {
            Ok(key) => {
                ui.set_d_password(s(""));
                ui.set_d_password2(s(""));
                ui.set_recovery_key(s(key));
                ui.set_dialog(3);
            }
            Err(e) => ui.set_d_error(s(e.to_string())),
        }
    });

    on!(on_year_changed, |ui, st, i: i32| {
        if let Some(y) = usize::try_from(i).ok().and_then(|i| st.years.get(i)) {
            st.year = *y;
            st.form = None;
            ui.set_form_editing(false);
            refresh(&ui, st);
        }
    });

    // Forms
    on!(on_new_form, |ui, st| {
        if st.payer_ids.is_empty() {
            show_message(&ui, 4, "Add the payer first: Payers → New payer.");
            return;
        }
        let f = Form {
            tax_year: st.year,
            payer: st.payer_ids.first().cloned().unwrap_or_default(),
            ..Form::default()
        };
        st.form = Some(f.clone());
        let mut shown = f;
        shown.recipient.clear();
        show_form(&ui, st, &shown);
        ui.set_f_recipient(-1);
    });

    on!(on_select_form, |ui, st, id: SharedString| {
        let Some(book) = st.book.as_mut() else { return };
        match book.form(&id) {
            Ok(f) => {
                st.form = Some(f.clone());
                show_form(&ui, st, &f);
            }
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_form_kind_changed, |ui, st, i: i32| {
        if let Some(f) = st.form.as_mut() {
            f.kind = if i == 1 {
                FormKind::Misc
            } else {
                FormKind::Nec
            };
            f.amounts.clear();
            f.checks.clear();
            f.ttoc.clear();
            ui.set_f_boxes(model(box_fields(f)));
        }
    });

    {
        let weak = ui.as_weak();
        ui.on_box_edited(move |i, t| {
            let Some(ui) = weak.upgrade() else { return };
            let rows = ui.get_f_boxes();
            if let Ok(i) = usize::try_from(i)
                && let Some(mut b) = rows.row_data(i)
            {
                b.value = t;
                rows.set_row_data(i, b);
            }
        });
    }
    {
        let weak = ui.as_weak();
        ui.on_box_toggled(move |i, on| {
            let Some(ui) = weak.upgrade() else { return };
            let rows = ui.get_f_boxes();
            if let Ok(i) = usize::try_from(i)
                && let Some(mut b) = rows.row_data(i)
            {
                b.checked = on;
                rows.set_row_data(i, b);
            }
        });
    }

    on!(on_save_form, |ui, st| {
        let f = match form_from_ui(&ui, st) {
            Ok(f) => f,
            Err(e) => return show_error(&ui, &e),
        };
        let Some(book) = st.book.as_mut() else { return };
        match book.save_form(f) {
            Ok(saved) => {
                st.year = saved.tax_year;
                st.form = Some(saved.clone());
                refresh(&ui, st);
                show_form(&ui, st, &saved);
                show_message(&ui, 3, "Saved.");
            }
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_mark_ready, |ui, st| {
        let Some(id) = st.form.as_ref().map(|f| f.id.clone()) else {
            return;
        };
        // Save what is on screen first.
        let f = match form_from_ui(&ui, st) {
            Ok(f) => f,
            Err(e) => return show_error(&ui, &e),
        };
        let Some(book) = st.book.as_mut() else { return };
        if let Err(e) = book.save_form(f) {
            return show_error(&ui, &e);
        }
        refresh(&ui, st);
        let blocked = st
            .loaded
            .as_ref()
            .and_then(|y| {
                y.forms
                    .iter()
                    .find(|f| f.id == id)
                    .map(|f| !check::can_be_ready(&y.findings, f))
            })
            .unwrap_or(true);
        if blocked {
            show_message(
                &ui,
                2,
                "Answer the checks shown on the form before marking it ready.",
            );
        } else if let Some(book) = st.book.as_mut() {
            match book.set_status(std::slice::from_ref(&id), Status::Ready) {
                Ok(_) => show_message(&ui, 3, "Marked ready."),
                Err(e) => show_error(&ui, &e),
            }
            refresh(&ui, st);
        }
        if let Some(book) = st.book.as_mut()
            && let Ok(f) = book.form(&id)
        {
            st.form = Some(f.clone());
            show_form(&ui, st, &f);
        }
    });

    on!(on_mark_all_ready, |ui, st| {
        let Some(y) = st.loaded.as_ref() else { return };
        let ids: Vec<String> = y
            .forms
            .iter()
            .filter(|f| f.status == Status::Draft && check::can_be_ready(&y.findings, f))
            .map(|f| f.id.clone())
            .collect();
        let waiting = y
            .forms
            .iter()
            .filter(|f| f.status == Status::Draft && !check::can_be_ready(&y.findings, f))
            .count();
        let Some(book) = st.book.as_mut() else { return };
        match book.set_status(&ids, Status::Ready) {
            Ok(n) => {
                let mut m = format!("{n} form(s) marked ready.");
                if waiting > 0 {
                    m.push_str(&format!(" {waiting} still need answers."));
                }
                show_message(&ui, if waiting > 0 { 4 } else { 3 }, m);
            }
            Err(e) => show_error(&ui, &e),
        }
        refresh(&ui, st);
    });

    on!(on_correct_form, |ui, st| {
        let Some(id) = st.form.as_ref().map(|f| f.id.clone()) else {
            return;
        };
        let Some(book) = st.book.as_mut() else { return };
        match book.correct(&id) {
            Ok(f) => {
                st.form = Some(f.clone());
                refresh(&ui, st);
                show_form(&ui, st, &f);
                show_message(
                    &ui,
                    4,
                    "Reopened as a correction. Change it, print a new Copy B for the recipient and \
                     file the correction in IRIS.",
                );
            }
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_close_form, |ui, st| {
        st.form = None;
        ui.set_form_editing(false);
        ui.set_selected_form(s(""));
    });

    // Payers and recipients
    on!(on_show_people, |ui, st, payers: bool| {
        ui.set_people_payers(payers);
        st.person = None;
        ui.set_person_editing(false);
        ui.set_selected_person(s(""));
        refresh_people(&ui, st);
    });

    on!(on_new_person, |ui, st| {
        let p = if ui.get_people_payers() {
            Person::Payer(Payer::default())
        } else {
            Person::Recipient(Recipient::default())
        };
        show_person(&ui, &p);
        st.person = Some(p);
    });

    on!(on_select_person, |ui, st, id: SharedString| {
        let Some(book) = st.book.as_mut() else { return };
        let p = if ui.get_people_payers() {
            book.payer(&id).map(Person::Payer)
        } else {
            book.recipient(&id).map(Person::Recipient)
        };
        match p {
            Ok(p) => {
                show_person(&ui, &p);
                st.person = Some(p);
            }
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_save_person, |ui, st| {
        let Some(base) = st.person.clone() else {
            return;
        };
        let edited = person_from_ui(&ui, &base);
        let Some(book) = st.book.as_mut() else { return };
        let saved = match edited {
            Person::Payer(p) => book.save_payer(p).map(Person::Payer),
            Person::Recipient(r) => book.save_recipient(r).map(Person::Recipient),
        };
        match saved {
            Ok(p) => {
                st.person = Some(p.clone());
                refresh(&ui, st);
                show_person(&ui, &p);
                show_message(&ui, 3, "Saved.");
            }
            Err(e) => show_error(&ui, &e),
        }
    });

    on!(on_close_person, |ui, st| {
        st.person = None;
        ui.set_person_editing(false);
        ui.set_selected_person(s(""));
    });

    on!(on_confirm_delete, |ui, st| {
        let which = ui.get_dialog();
        ui.set_dialog(0);
        let Some(book) = st.book.as_mut() else { return };
        let r = if which == 5 {
            let id = st.form.as_ref().map(|f| f.id.clone()).unwrap_or_default();
            book.delete_form(&id).map(|()| {
                st.form = None;
                ui.set_form_editing(false);
            })
        } else {
            match &st.person {
                Some(Person::Payer(p)) => book.delete_payer(&p.id),
                Some(Person::Recipient(r)) => book.delete_recipient(&r.id),
                None => Ok(()),
            }
            .map(|()| {
                st.person = None;
                ui.set_person_editing(false);
            })
        };
        match r {
            Ok(()) => show_message(&ui, 3, "Deleted."),
            Err(e) => show_error(&ui, &e),
        }
        refresh(&ui, st);
    });

    // Import
    on!(on_choose_mk_book, |ui, _st| {
        if let Some(p) = rfd::FileDialog::new()
            .set_title("Choose the MoneyKeep book")
            .add_filter("MoneyKeep book", &[form1099keep::BOOK_EXTENSION])
            .pick_file()
        {
            ui.set_im_encrypted(matches!(
                mk_store::book_kind(&p),
                Ok(mk_store::BookKind::Encrypted)
            ));
            ui.set_im_path(s(p.display().to_string()));
        }
    });

    on!(on_run_import, |ui, st| {
        let path = PathBuf::from(ui.get_im_path().trim());
        let year: i32 = match ui.get_im_year().trim().parse() {
            Ok(y) => y,
            Err(_) => return show_message(&ui, 2, "The tax year should be a year such as 2026."),
        };
        let Some(payer) = usize::try_from(ui.get_im_payer())
            .ok()
            .and_then(|i| st.payer_ids.get(i).cloned())
        else {
            return show_message(&ui, 2, "Choose the payer.");
        };
        let encrypted = matches!(
            mk_store::book_kind(&path),
            Ok(mk_store::BookKind::Encrypted)
        );
        ui.set_im_encrypted(encrypted);
        let pw = ui.get_im_password().to_string();
        if encrypted && pw.is_empty() {
            return show_message(
                &ui,
                4,
                "That MoneyKeep book is password protected: enter its password.",
            );
        }
        let Some(book) = st.book.as_mut() else { return };
        let opts = import::Options {
            path,
            password: encrypted.then_some(pw),
            year,
            payer,
            include_below_threshold: ui.get_im_all(),
        };
        match import::import_moneykeep(book, &opts) {
            Ok(r) => {
                ui.set_im_password(s(""));
                let mut notes = vec![note(
                    3,
                    format!("From “{}”, {}: {}", r.book_name, r.year, r.summary()),
                )];
                for n in &r.notes {
                    notes.push(note(4, n.as_str()));
                }
                for (k, (mk, us)) in &r.threshold_differences {
                    notes.push(note(1, format!("{k}: MoneyKeep's threshold is ${mk}; the IRS amount used here is ${us}.")));
                }
                if !r.below_threshold.is_empty() {
                    notes.push(note(
                        1,
                        format!(
                            "Below the threshold (not imported): {}",
                            r.below_threshold.join(", ")
                        ),
                    ));
                }
                if !r.already_filed.is_empty() {
                    notes.push(note(
                        1,
                        format!("Already filed (left alone): {}", r.already_filed.join(", ")),
                    ));
                }
                ui.set_im_result(model(notes));
                st.year = year;
                refresh(&ui, st);
                show_message(&ui, 3, "Imported. Answer the checks on each form (Forms).");
            }
            Err(e) => {
                ui.set_im_result(model(vec![note(2, e.to_string())]));
            }
        }
    });

    // Print and e-file
    on!(on_print_copies, |ui, st| {
        let mut copies = Vec::new();
        for (on, c) in [
            (ui.get_copy_b(), pdf::Copy::B),
            (ui.get_copy_1(), pdf::Copy::One),
            (ui.get_copy_2(), pdf::Copy::Two),
            (ui.get_copy_c(), pdf::Copy::C),
        ] {
            if on {
                copies.push(c);
            }
        }
        if copies.is_empty() {
            return show_message(&ui, 2, "Choose at least one copy.");
        }
        let Some(y) = st.loaded.as_ref() else { return };
        let printed = match jobs::print(
            y,
            &[],
            &pdf::Options {
                copies,
                truncate_recipient_tin: ui.get_truncate_tin(),
            },
        ) {
            Ok(p) => p,
            Err(e) => return ui.set_out_result(model(vec![note(2, e.to_string())])),
        };
        let Some(path) = rfd::FileDialog::new()
            .set_title("Save recipient copies")
            .set_file_name(format!("1099 recipient copies {}.pdf", y.year))
            .add_filter("PDF", &["pdf"])
            .save_file()
        else {
            return;
        };
        let mut notes = Vec::new();
        match std::fs::write(&path, &printed.pdf) {
            Ok(()) => notes.push(note(
                3,
                format!(
                    "Saved {} — {} form(s), {} page(s).",
                    path.display(),
                    printed.forms,
                    printed.pages
                ),
            )),
            Err(e) => notes.push(note(2, format!("Cannot write {}: {e}", path.display()))),
        }
        for x in &printed.skipped {
            notes.push(note(4, format!("Left out {}: {}", x.label, x.reason)));
        }
        ui.set_out_result(model(notes));
    });

    on!(on_choose_template, |ui, _st| {
        if let Some(p) = rfd::FileDialog::new()
            .set_title("Choose the CSV template downloaded from the IRIS portal")
            .add_filter("CSV", &["csv"])
            .pick_file()
        {
            ui.set_ir_template(s(p.display().to_string()));
        }
    });

    on!(on_save_iris, |ui, st| {
        let kind = if ui.get_ir_kind() == 1 {
            FormKind::Misc
        } else {
            FormKind::Nec
        };
        let payer = usize::try_from(ui.get_ir_payer())
            .ok()
            .and_then(|i| st.payer_ids.get(i).cloned());
        let tpl_path = ui.get_ir_template().trim().to_owned();
        let template = if tpl_path.is_empty() {
            None
        } else {
            match iris::read_template(Path::new(&tpl_path)) {
                Ok(t) => Some(t),
                Err(e) => return ui.set_out_result(model(vec![note(2, e.to_string())])),
            }
        };
        let Some(y) = st.loaded.as_ref() else { return };
        let files = match jobs::iris_files(y, kind, payer.as_deref(), template) {
            Ok(f) => f,
            Err(e) => return ui.set_out_result(model(vec![note(2, e.to_string())])),
        };
        let Some(folder) = rfd::FileDialog::new()
            .set_title("Choose a folder for the IRIS files")
            .pick_folder()
        else {
            return;
        };
        let mut notes = Vec::new();
        match iris::write_files(&folder, &files.built.files) {
            Ok(paths) => {
                notes.push(note(
                    3,
                    format!(
                        "{} form(s) in {} file(s) in {}.",
                        files.rows,
                        paths.len(),
                        folder.display()
                    ),
                ));
                for p in paths {
                    notes.push(note(1, p.display().to_string()));
                }
            }
            Err(e) => notes.push(note(2, e.to_string())),
        }
        if files.builtin_headers {
            notes.push(note(
                4,
                "Built with Form1099Keep's draft columns. The IRS accepts only its own template: \
                 download this year's template in the IRIS portal and choose it above before uploading.",
            ));
        }
        for h in &files.built.unmapped {
            notes.push(note(
                4,
                format!("Left blank (column not known to Form1099Keep): {h}"),
            ));
        }
        for h in &files.built.unconfirmed {
            notes.push(note(
                4,
                format!("Check this column's value against the IRS guidelines: {h}"),
            ));
        }
        for x in &files.skipped {
            notes.push(note(4, format!("Left out {}: {}", x.label, x.reason)));
        }
        ui.set_out_result(model(notes));
    });

    on!(on_mark_filed, |ui, st| {
        let Some(y) = st.loaded.as_ref() else { return };
        let ids: Vec<String> = y
            .forms
            .iter()
            .filter(|f| f.status == Status::Ready)
            .map(|f| f.id.clone())
            .collect();
        let date = ui.get_filed_date().trim().to_owned();
        let receipt = ui.get_filed_receipt().trim().to_owned();
        let Some(book) = st.book.as_mut() else { return };
        match book.mark_filed(&ids, &date, &receipt) {
            Ok(n) => {
                ui.set_out_result(model(vec![note(
                    3,
                    format!("Marked {n} form(s) filed on {date}."),
                )]));
                ui.set_filed_receipt(s(""));
            }
            Err(e) => show_error(&ui, &e),
        }
        refresh(&ui, st);
    });

    on!(on_refresh_history, |ui, st| {
        let Some(book) = st.book.as_mut() else { return };
        let rows: Vec<HistoryRow> = book
            .history(300)
            .unwrap_or_default()
            .into_iter()
            .map(|h| HistoryRow {
                when: s(format!(
                    "{} UTC",
                    h.at.get(..16).unwrap_or_default().replace('T', " ")
                )),
                what: s(h
                    .command
                    .trim_start_matches("f1099.")
                    .replace(['.', '_'], " ")),
                detail: s(h.summary),
            })
            .collect();
        ui.set_history(model(rows));
    });
}

fn main() -> Result<(), slint::PlatformError> {
    let ui = AppWindow::new()?;
    let state: Shared = Rc::new(RefCell::new(State {
        config: Config::load(),
        year: default_year(),
        ..State::default()
    }));
    wire(&ui, &state);
    ui.set_filed_date(s(today()));
    ui.set_im_year(s(default_year().to_string()));
    {
        let mut st = state.borrow_mut();
        refresh(&ui, &mut st);
    }
    if let Ok(size) = std::env::var("F1099KEEP_SIZE")
        && let Some((w, h)) = size.split_once('x')
        && let (Ok(w), Ok(h)) = (w.parse::<u32>(), h.parse::<u32>())
    {
        ui.window().set_size(slint::PhysicalSize::new(w, h));
    }
    if let Ok(p) = std::env::var("F1099KEEP_OPEN") {
        let pw = std::env::var("F1099KEEP_PASSWORD").ok();
        let mut st = state.borrow_mut();
        match Book::open(Path::new(&p), pw.as_deref()) {
            Ok(b) => opened(&ui, &mut st, b),
            Err(e) => show_error(&ui, &e),
        }
    }
    if let Some(n) = std::env::var("F1099KEEP_FORM")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
        && let Some(row) = ui.get_forms().row_data(n)
    {
        ui.invoke_select_form(row.id);
    }
    if let Some(n) = std::env::var("F1099KEEP_PERSON")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
    {
        ui.invoke_show_people(false);
        ui.set_section(2);
        if let Some(row) = ui.get_people().row_data(n) {
            ui.invoke_select_person(row.id);
        }
    }
    if let Ok(sec) = std::env::var("F1099KEEP_SECTION")
        && let Ok(n) = sec.parse::<i32>()
    {
        ui.set_section(n);
        if n == 0 || n == 2 {
            ui.invoke_show_people(n == 0);
        }
        if n == 5 {
            ui.invoke_refresh_history();
        }
    }
    ui.run()
}

